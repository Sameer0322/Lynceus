-- H2 schema for local development and Render deployment.
-- Loaded via spring.sql.init.schema-locations in application.yaml.

CREATE TABLE IF NOT EXISTS PIPELINE_DB_APPUSERS (
    USERNAME      VARCHAR(64)  NOT NULL,
    PASSWORDHASH  VARCHAR(72),
    ROLE          VARCHAR(16)  DEFAULT 'viewer',
    CREATEDAT     TIMESTAMP,
    LASTLOGIN     TIMESTAMP,
    PRIMARY KEY (USERNAME)
);

CREATE TABLE IF NOT EXISTS PIPELINE_DB_AUDITLOG (
    ID        VARCHAR(36)  NOT NULL,
    ACTION    VARCHAR(32),
    USERNAME  VARCHAR(64),
    TARGET    VARCHAR(256),
    TIMESTAMP TIMESTAMP,
    META      TEXT,
    PRIMARY KEY (ID)
);

CREATE TABLE IF NOT EXISTS PIPELINE_DB_TEAMS (
    ID    VARCHAR(36)  NOT NULL,
    NAME  VARCHAR(128),
    PRIMARY KEY (ID)
);

CREATE TABLE IF NOT EXISTS PIPELINE_DB_TEAMREPOS (
    ID      VARCHAR(36)  NOT NULL,
    TEAMID  VARCHAR(36),
    REPO    VARCHAR(256),
    PRIMARY KEY (ID)
);

CREATE TABLE IF NOT EXISTS PIPELINE_DB_RELEASEGROUPS (
    ID         VARCHAR(36)  NOT NULL,
    NAME       VARCHAR(128),
    CREATEDBY  VARCHAR(64),
    CREATEDAT  TIMESTAMP,
    PRIMARY KEY (ID)
);

CREATE TABLE IF NOT EXISTS PIPELINE_DB_RELEASEPIPELINES (
    ID           VARCHAR(36)  NOT NULL,
    GROUPID      VARCHAR(36),
    RUNID        VARCHAR(32),
    REPO         VARCHAR(256),
    BRANCH       VARCHAR(128),
    RUNNUMBER    INT,
    MESSAGE      VARCHAR(512),
    ADDEDBY      VARCHAR(128),
    ADDEDAT      TIMESTAMP,
    NOTE         VARCHAR(1024),
    DISPLAYORDER INT DEFAULT 0,
    PRIMARY KEY (ID)
);
